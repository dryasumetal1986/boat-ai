import streamlit as st
import pandas as pd

import data
from ai import tri_ai


# =========================================================
# ページ設定
# =========================================================

st.set_page_config(
    page_title="やっちゃんの競艇AI予想PRO",
    page_icon="🚤",
    layout="centered",
)


# =========================================================
# 会場
# =========================================================

STADIUMS = {
    1: "桐生",
    2: "戸田",
    3: "江戸川",
    4: "平和島",
    5: "多摩川",
    6: "浜名湖",
    7: "蒲郡",
    8: "常滑",
    9: "津",
    10: "三国",
    11: "びわこ",
    12: "住之江",
    13: "尼崎",
    14: "鳴門",
    15: "丸亀",
    16: "児島",
    17: "宮島",
    18: "徳山",
    19: "下関",
    20: "若松",
    21: "芦屋",
    22: "福岡",
    23: "唐津",
    24: "大村",
}


# =========================================================
# タイトル
# =========================================================

st.title("🚤 やっちゃんのAI予想PRO")


# =========================================================
# 開催日
# =========================================================

today = pd.Timestamp.now().date()

target_date = st.date_input(
    "開催日",
    value=today,
)


# =========================================================
# 会場・R
# =========================================================

col1, col2 = st.columns(2)

with col1:

    # 表示は「桐生」「戸田」のように名前だけ
    stadium_name_selected = st.selectbox(
        "場",
        list(STADIUMS.values()),
    )

    # 名前から場番号を取得
    stadium_no = next(
        no
        for no, name in STADIUMS.items()
        if name == stadium_name_selected
    )


with col2:

    race_no = st.selectbox(
        "R",
        list(range(1, 13)),
        format_func=lambda x: f"{x}R",
    )


# =========================================================
# AI予想ボタン
# =========================================================

if st.button(
    "🚤 AI予想する",
    type="primary",
    use_container_width=True,
):

    # -----------------------------------------------------
    # データ取得
    # -----------------------------------------------------

    try:

        raw = data.get_data(
            target_date
        )

    except Exception as e:

        st.error(
            "データを取得できませんでした。"
        )

        st.stop()


    # -----------------------------------------------------
    # 指定会場・指定Rを取得
    # -----------------------------------------------------

    try:

        race = data.get_race(
            raw,
            stadium_no,
            race_no,
        )

    except Exception:

        st.error(
            f"{stadium_name_selected} {race_no}R "
            "のデータが見つかりません。"
        )

        st.stop()


    # -----------------------------------------------------
    # レース確認
    # -----------------------------------------------------

    try:

        valid, message = data.validate_race(
            race,
            stadium_no,
            race_no,
            target_date,
        )

    except Exception:

        valid = False
        message = "レースデータの確認に失敗しました。"


    if not valid:

        st.error(
            "選択したレースのデータが正しくありません。"
        )

        st.stop()


    # -----------------------------------------------------
    # 選手取得
    # -----------------------------------------------------

    try:

        df = data.get_race_rows(
            race,
            stadium_no,
            race_no,
            target_date,
        )

    except Exception:

        st.error(
            "出走選手データを取得できませんでした。"
        )

        st.stop()


    # -----------------------------------------------------
    # 6艇確認
    # -----------------------------------------------------

    if len(df) != 6:

        st.error(
            "6艇の出走選手を取得できませんでした。"
        )

        st.stop()


    # =====================================================
    # 過去データ
    # =====================================================

    try:

        history = data.history14(
            target_date
        )

    except Exception:

        history = pd.DataFrame()


    # =====================================================
    # AI予想
    # =====================================================

    try:

        result, boat_probs = tri_ai(
            df,
            history,
        )

    except Exception:

        st.error(
            "AI予想の計算に失敗しました。"
        )

        st.stop()


    # =====================================================
    # レースタイトル
    # =====================================================

    st.markdown("---")

    st.subheader(
        f"{stadium_name_selected} {race_no}R"
    )


    # =====================================================
    # 6選手
    # =====================================================

    for _, row in df.iterrows():

        lane = int(row["枠"])
        name = row["選手名"]

        st.markdown(
            f"**{lane}号艇　{name}**"
        )


    # =====================================================
    # 上位3予想
    # =====================================================

    st.markdown("---")

    if len(result) >= 3:

        main = result.iloc[0]
        second = result.iloc[1]
        hole = result.iloc[2]

        # -------------------------------------------------
        # 本命
        # -------------------------------------------------

        st.markdown("### 🎯 本命")

        st.markdown(
            f"# {main['買い目']}"
        )


        # -------------------------------------------------
        # 対抗
        # -------------------------------------------------

        st.markdown("### 🔥 対抗")

        st.markdown(
            f"## {second['買い目']}"
        )


        # -------------------------------------------------
        # 穴
        # -------------------------------------------------

        st.markdown("### 💥 穴")

        st.markdown(
            f"## {hole['買い目']}"
        )


    # =====================================================
    # AI自信度
    # =====================================================

    # 上位3点の確率差を利用
    try:

        p1 = float(result.iloc[0]["確率"])
        p2 = float(result.iloc[1]["確率"])
        p3 = float(result.iloc[2]["確率"])

        gap = p1 - p2

        if gap >= 2.0:
            confidence = "★★★★★"

        elif gap >= 1.0:
            confidence = "★★★★☆"

        elif gap >= 0.5:
            confidence = "★★★☆☆"

        elif gap >= 0.2:
            confidence = "★★☆☆☆"

        else:
            confidence = "★☆☆☆☆"

    except Exception:

        confidence = "★★★☆☆"


    # =====================================================
    # 自信度表示
    # =====================================================

    st.markdown("---")

    st.markdown(
        f"### AI自信度　{confidence}"
    )
